"""Generate the M-CRT MiSTer video preset (filters + gamma curve) into dist/.

The numbers mirror the RetroArch m-crt shader defaults
(https://github.com/md0-code/m-crt, shaders/m-crt.retroarch.slang).
"""
import argparse
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAME = "M-CRT"
PHASES = 64

# m-crt defaults
BLUR_STRENGTH = 0.8
SCANLINES_STRENGTH = 0.05
GAMMA = 0.8
# Average gain of the shader's 3-column stripe (1.005, 1.020, 1.035); the
# individual steps are below the MiSTer shadow mask's 1/16 resolution.
STRIPE_GAIN = (1.005 + 1.020 + 1.035) / 3

# 3x3 gaussian (sigma 1) used by the shader, collapsed to one axis.
SIDE = 0.077847 * 2 + 0.123317
CENTER = 0.123317 * 2 + 0.195346


def smoothstep(e0, e1, x):
    t = min(max((x - e0) / (e1 - e0), 0.0), 1.0)
    return t * t * (3 - 2 * t)


def taps(phase, blur_src, gain):
    """4-tap weights for an output pixel sitting at `phase` (0..1) between
    source pixels 1 and 2: nearest-neighbour fetches at -b, 0, +b."""
    w = [0.0] * 4
    total = SIDE * 2 + CENTER
    for offset, weight in ((-blur_src, SIDE), (0.0, CENTER), (blur_src, SIDE)):
        idx = math.floor(phase + offset + 0.5) + 1
        w[min(max(idx, 0), 3)] += weight / total
    return [x * gain for x in w]


def quantize(weights, unit=256):
    q = [round(x * unit) for x in weights]
    target = round(sum(weights) * unit)
    q[q.index(max(q))] += target - sum(q)
    return q


def filter_file(title, rows):
    lines = ["10bit", "", f"# {NAME} {title}", "# Generated by tools/build.py from the m-crt shader defaults", ""]
    lines += ["{:4d},{:4d},{:4d},{:4d}".format(*quantize(r)) for r in rows]
    return "\n".join(lines) + "\n"


def build(output_height, source_height, aspect):
    scale = output_height / source_height
    # Shader blur offset is BLUR_STRENGTH / viewport aspect, in output pixels.
    blur_src = BLUR_STRENGTH / aspect / scale
    # Shader hides scanlines below 360 output lines.
    amp = SCANLINES_STRENGTH if output_height >= 360 else 0.0

    h_rows, v_rows = [], []
    for i in range(PHASES):
        ph = i / PHASES
        h_rows.append(taps(ph, blur_src, 1.0))
        # Scanline locked to source lines: brightest at line centre. MiSTer
        # applies gamma before the scaler, so the shader's pre-gamma modulation
        # is raised to GAMMA here.
        gain = (1 + amp * math.cos(2 * math.pi * ph)) ** GAMMA
        v_rows.append(taps(ph, blur_src, gain))

    gamma = ["# M-CRT gamma: out = 255 * min(1, (stripe_gain * in / 255) ^ 0.8)"]
    gamma += [str(round(255 * min(1.0, (STRIPE_GAIN * i / 255) ** GAMMA))) for i in range(256)]

    preset = "\n".join([
        f"# {NAME}: approximation of the m-crt shader (https://github.com/md0-code/m-crt)",
        f"# Tuned for {output_height}p output and {source_height}-line sources",
        f"hfilter={NAME}/{NAME}_H.txt",
        f"vfilter={NAME}/{NAME}_V.txt",
        "sfilter=same",
        f"gamma={NAME}/{NAME}.txt",
        "mask=off",
        "maskmode=off",
    ]) + "\n"

    out = {
        f"Filters/{NAME}/{NAME}_H.txt": filter_file("horizontal: soft nearest-neighbour edges", h_rows),
        f"Filters/{NAME}/{NAME}_V.txt": filter_file("vertical: soft edges + 5% scanlines", v_rows),
        f"Gamma/{NAME}/{NAME}.txt": "\n".join(gamma) + "\n",
        f"Presets/{NAME}.ini": preset,
    }
    dist = ROOT / "dist"
    for rel, text in out.items():
        path = dist / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, newline="\n")
        print(path.relative_to(ROOT))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--output-height", type=int, default=720, help="MiSTer HDMI output height (video_mode)")
    ap.add_argument("--source-height", type=int, default=240, help="typical core line count")
    ap.add_argument("--aspect", type=float, default=4 / 3, help="game viewport aspect")
    a = ap.parse_args()
    build(a.output_height, a.source_height, a.aspect)


if __name__ == "__main__":
    main()
